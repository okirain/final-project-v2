"""
    ISRDesign

Design-space exploration for the passive heat-pipe retrofit of the Indonesian
Space Reactor (ISR) of Khandaq et al. (2020).

Baseline (ISR Mark 1)
---------------------
* 500 kWth, 61 hexagonal UN fuel pins (55 % U-235), Mo-30Re cladding;
* active core height 25 cm, pin pitch / flat-to-flat 3.4 cm;
* individual rhenium-lined coolant channel, 0.6 cm ID, 0.08 cm wall;
* pumped Na-78K loop, 750 K inlet / 950 K outlet.

The Mark 2 study replaces the pumped loop by alkali-metal heat pipes.  The
central question is whether the 8.2 kWth generated by one pin can be removed
through the existing 0.6 cm channel.  The module answers that question for
Na, K and Li, several wick architectures and a 900-1200 K outlet envelope,
and then quantifies three architectural options.
"""
module ISRDesign

using JSON3
using ..FluidProperties
using ..Wick
using ..Limits

export ISRCore, isr_core, isr_pin_power, isr_heatpipe, isr_feasibility,
       isr_required_diameter, isr_diameter_sweep, isr_fluid_comparison,
       isr_options, isr_mass_balance, channel_area, fuel_annulus_area

"""
    ISRCore

Parsed ISR baseline specification (SI units internally).
"""
struct ISRCore
    P_th::Float64          # W
    n_pins::Int
    core_height::Float64   # m
    pitch::Float64         # m
    pin_ff::Float64        # m
    clad_height::Float64   # m
    T_in::Float64          # K
    T_out::Float64         # K
    cavity_D::Float64      # m
    channel_id::Float64    # m
    channel_wall::Float64  # m
    fuel_od::Float64       # m
    fuel_id::Float64       # m
    enrichment::Float64    # percent
    mass::Float64          # kg
    excess_reactivity::Float64 # pcm
    beta::Float64
end

"""
    isr_core(path = data/isr_specs.json) -> ISRCore

Load the ISR specification from JSON.
"""
function isr_core(path::AbstractString = joinpath(@__DIR__, "..", "data", "isr_specs.json"))
    j = JSON3.read(read(path, String))
    r = j.reactor
    p = j.pin
    return ISRCore(1000.0 * Float64(r.thermal_power_kW),
                   Int(r.n_pins),
                   1e-2 * Float64(r.core_active_height_cm),
                   1e-2 * Float64(r.pin_pitch_cm),
                   1e-2 * Float64(r.pin_flat_to_flat_cm),
                   1e-2 * Float64(r.clad_height_cm),
                   Float64(r.T_inlet_K), Float64(r.T_outlet_K),
                   1e-2 * Float64(p.cavity_diameter_cm),
                   1e-2 * Float64(p.coolant_channel_id_cm),
                   1e-2 * Float64(p.coolant_channel_wall_cm),
                   1e-2 * Float64(p.fuel_outer_diameter_cm),
                   1e-2 * Float64(p.fuel_inner_diameter_cm),
                   Float64(p.enrichment_pct),
                   Float64(r.reactor_mass_kg),
                   Float64(r.excess_reactivity_pcm),
                   Float64(r.beta_effective))
end

"""Average thermal power per fuel pin, W."""
isr_pin_power(c::ISRCore) = c.P_th / c.n_pins

"""Cross-sectional area of the existing coolant channel, m^2."""
channel_area(c::ISRCore) = pi * (c.channel_id / 2)^2

"""Cross-sectional area of the annular fuel pellet, m^2."""
fuel_annulus_area(c::ISRCore) = pi * ((c.fuel_od / 2)^2 - (c.fuel_id / 2)^2)

# ---------------------------------------------------------------------------
# Heat-pipe constructor for the retrofit
# ---------------------------------------------------------------------------

"""
    isr_heatpipe(f; D_out = 0.006, wick = :arterial, L_e = 0.25, L_a = 0.30,
                 L_c = 0.45, T_sink = 600.0)

Build an ISR heat pipe of outer diameter `D_out`.

Wick options:

* `:arterial`  - high-permeability artery (`K = 1e-7 m^2`) with 50 micron
  surface pores (best performance, but artery de-priming is a failure mode);
* `:annular`   - annular gap with a fine surface mesh (`r_pore = t/8`);
* `:sintered`  - 50 micron sintered powder (`epsilon = 0.40`).

The wall thickness is 6 % of the diameter and the wick thickness 8 %, leaving
the rest as vapour core.
"""
function isr_heatpipe(f::Fluid; D_out::Real = 0.006, wick::Symbol = :arterial,
                      L_e::Real = 0.25, L_a::Real = 0.30, L_c::Real = 0.45,
                      T_sink::Real = 600.0)
    D = float(D_out)
    r_o = D / 2
    t_wall = clamp(0.06 * D, 2.0e-4, 1.0e-3)
    t_wick = 0.08 * D
    r_i = r_o - t_wall
    r_v = r_i - t_wick
    r_v = max(r_v, 0.25 * r_o)

    w = if wick == :arterial
        WickGeometry(:arterial, 5.0e-5, 1.0e-7, 0.70, t_wick, 25.0)
    elseif wick == :annular
        WickGeometry(:annular, t_wick / 8.0, t_wick^2 / 12.0, 1.0, t_wick, 25.0)
    elseif wick == :sintered
        ww = sintered_wick(5.0e-5; epsilon = 0.40, k_s = 25.0, t = t_wick)
        WickGeometry(:sintered, ww.r_eff, ww.K, ww.epsilon, t_wick, 25.0)
    else
        throw(ArgumentError("unknown wick type $wick"))
    end

    return HeatPipe(f, D, t_wall, w;
                    L_e = L_e, L_a = L_a, L_c = L_c, r_v = r_v,
                    k_wall = 25.0, rho_wall = 8900.0, cp_wall = 420.0,
                    T_sink = T_sink, g = 0.0, orientation = 0.0,
                    thermosyphon = false)
end

# ---------------------------------------------------------------------------
# Feasibility
# ---------------------------------------------------------------------------

"""
    isr_feasibility(; T = 1200.0, D = 0.006, Q_req = nothing)

Evaluate the maximum throughput of a single heat pipe that fits the existing
0.6 cm channel, for Na, K and Li and the three wick architectures.  Returns a
vector of named tuples with `fluid`, `wick`, `Q_max`, `Q_req`, `ratio`.
"""
function isr_feasibility(; T::Real = 1200.0, D::Real = 0.006,
                         Q_req::Union{Nothing,Real} = nothing)
    c = isr_core()
    Qr = Q_req === nothing ? isr_pin_power(c) : float(Q_req)
    rows = NamedTuple[]
    for f in (Na, K, Li), w in (:arterial, :annular, :sintered)
        hp = isr_heatpipe(f; D_out = D, wick = w)
        lim = operating_limits(hp, T)
        push!(rows, (fluid = f.name, wick = w, T = float(T),
                     Q_max = lim.minimum, Q_req = Qr,
                     ratio = lim.minimum / Qr, controlling = lim.controlling))
    end
    return rows
end

"""
    isr_required_diameter(f; T = 1200.0, Q_req = nothing, wick = :arterial,
                          Dmin = 0.004, Dmax = 0.12)

Smallest outer diameter whose controlling limit reaches `Q_req`, found by
bisection on `D`.
"""
function isr_required_diameter(f::Fluid; T::Real = 1200.0,
                               Q_req::Union{Nothing,Real} = nothing,
                               wick::Symbol = :arterial,
                               Dmin::Real = 0.004, Dmax::Real = 0.12)
    c = isr_core()
    Qr = Q_req === nothing ? isr_pin_power(c) : float(Q_req)
    qmax(D) = max_power(isr_heatpipe(f; D_out = D, wick = wick), T)

    if qmax(Dmax) < Qr
        return (D_required = NaN, Q_at_Dmax = qmax(Dmax), achieved = false)
    end
    if qmax(Dmin) >= Qr
        return (D_required = Dmin, Q_at_Dmin = qmax(Dmin), achieved = true)
    end
    lo, hi = float(Dmin), float(Dmax)
    for _ in 1:80
        mid = 0.5 * (lo + hi)
        if qmax(mid) >= Qr
            hi = mid
        else
            lo = mid
        end
    end
    return (D_required = hi, Q_at_D = qmax(hi), achieved = true)
end

"""
    isr_diameter_sweep(f; T = 1200.0, wick = :arterial,
                       D = 0.004:0.001:0.04)

Power limit versus diameter for one fluid and wick.
"""
function isr_diameter_sweep(f::Fluid; T::Real = 1200.0, wick::Symbol = :arterial,
                            D::AbstractRange = 0.004:0.001:0.04)
    return [(D = d, Q = max_power(isr_heatpipe(f; D_out = d, wick = wick), T))
            for d in D]
end

"""
    isr_fluid_comparison(; D = 0.006, wick = :arterial,
                         T = [900, 1000, 1100, 1200])

Table of power limits versus fluid and outlet temperature.
"""
function isr_fluid_comparison(; D::Real = 0.006, wick::Symbol = :arterial,
                              T = [900.0, 1000.0, 1100.0, 1200.0])
    rows = NamedTuple[]
    for f in (Na, K, Li), TT in T
        hp = isr_heatpipe(f; D_out = D, wick = wick)
        lim = operating_limits(hp, TT)
        push!(rows, (fluid = f.name, T = float(TT), Q_max = lim.minimum,
                     controlling = lim.controlling))
    end
    return rows
end

