# Architectural options
# ---------------------------------------------------------------------------

"""
    isr_options(; T = 1200.0)

Quantify the three retrofit architectures.

* **Option A** - retain 61 pins and enlarge the central channel to the
  diameter required for 8.2 kW per pin (arterial sodium wick).
* **Option B** - keep the 0.6 cm channels and add 1.27 cm interstitial heat
  pipes in a widened hexagonal matrix.
* **Option C** - keep the existing geometry and down-rate the reactor to the
  capacity of 61 central heat pipes (or operate a hybrid passive/pumped
  system).

All quantities are first-order engineering estimates; the neutronic penalty is
reported as a fuel-volume / leakage indicator and must be confirmed with a
dedicated Monte Carlo model.
"""
function isr_options(; T::Real = 1200.0)
    c = isr_core()
    Qpin = isr_pin_power(c)

    # ---- Option A ---------------------------------------------------------
    a = isr_required_diameter(Na; T = T, Q_req = Qpin, wick = :arterial)
    r_ch = a.D_required / 2
    r_fuel_out = c.fuel_od / 2
    r_fuel_in_old = c.fuel_id / 2
    A_old = pi * (r_fuel_out^2 - r_fuel_in_old^2)
    A_new = max(pi * (r_fuel_out^2 - r_ch^2), 0.0)
    fuel_retained = A_new / A_old
    enrichment_needed = c.enrichment / max(fuel_retained, 1e-6)
    equiv_enrichment = c.enrichment * (1 + (1 - fuel_retained) * 0.85)
    optionA = (D_required = a.D_required, achieved = a.achieved,
               fuel_fraction_retained = fuel_retained,
               fuel_loss_pct = 100 * (1 - fuel_retained),
               enrichment_naive_pct = enrichment_needed,
               enrichment_realistic_pct = equiv_enrichment,
               note = "Enlarging the channel consumes the annular fuel; " *
                      "restoring reactivity needs ~30 % more U-235 or a longer core.")

    # ---- Option B ---------------------------------------------------------
    # A 4-ring (61-pin) hexagonal array has 6R^2 = 96 triangular interstices;
    # the 6R = 24 sites on the outer boundary are excluded (not fully ringed by
    # three pins), leaving 72 fully interior sites for interstitial heat pipes.
    n_int = 72                       # interior interstitial sites, 61-pin array
    Q_int_req = c.P_th / n_int
    bsize = isr_required_diameter(Na; T = T, Q_req = Q_int_req,
                                  wick = :arterial)
    D_int = bsize.D_required
    hp_int = isr_heatpipe(Na; D_out = D_int, wick = :arterial)
    Q_int = max_power(hp_int, T)
    Q_B = n_int * Q_int
    pitch_B = c.pin_ff + D_int + 0.002   # 2 mm assembly clearance
    width_old = (2 * 4 + 1) * c.pitch
    width_new = (2 * 4 + 1) * pitch_B
    core_block_mass_new = 50.8 * (width_new / width_old)^2
    # The radial reflector and drums are annular: at constant thickness their
    # mass scales with the circumference, not with the enclosed area.
    reflector_mass_new = 194.37 * (width_new / width_old)
    optionB = (D_interstitial = D_int, Q_per_pipe = Q_int, n_pipes = n_int,
               Q_total = Q_B, margin = Q_B / c.P_th - 1,
               pitch_new = pitch_B, width_old = width_old, width_new = width_new,
               core_block_mass_delta = core_block_mass_new - 50.8,
               reflector_mass_delta = reflector_mass_new - 194.37,
               D_required_for_500kW = D_int,
               note = "72 interstitial pipes sized for 500 kWth/72 each can " *
                      "carry the full thermal power; the penalty is a larger, " *
                      "heavier core.")

    # ---- Option C ---------------------------------------------------------
    hp_c = isr_heatpipe(Na; D_out = c.channel_id, wick = :arterial)
    Q_C = c.n_pins * max_power(hp_c, T)
    optionC = (n_pipes = c.n_pins,
               Q_per_pipe = max_power(hp_c, T),
               Q_total = Q_C,
               fraction_of_500kW = Q_C / c.P_th,
               note = "The existing 0.6 cm channels can remove only a fraction " *
                      "of the nominal power; 500 kWth requires either a hybrid " *
                      "loop or a down-rated mission.")

    return (T = float(T), Q_pin = Qpin, A = optionA, B = optionB, C = optionC)
end

# ---------------------------------------------------------------------------
# Mass and parasitic balance
# ---------------------------------------------------------------------------

"""
    isr_mass_balance(; T = 1200.0)

First-order comparison between the Mark 1 pumped Na-78K loop and a Mark 2
heat-pipe system.

Pumped loop
    mdot = Q / (cp dT); P_pump = mdot dP / (rho eta).
Heat-pipe system
    envelope + wick mass of the required number of pipes, plus a 30 %
    allowance for headers and mounting hardware.
"""
function isr_mass_balance(; T::Real = 1200.0)
    c = isr_core()
    Q = c.P_th
    cp_nak = 1000.0            # J/(kg K), Na-78K eutectic (engineering value)
    dT = c.T_out - c.T_in      # 200 K
    rho_nak = 750.0            # kg/m^3 at ~850 K
    dP = 30.0e3                # Pa, core + loop pressure drop (assumption)
    eta_pump = 0.35

    mdot = Q / (cp_nak * dT)
    P_pump = mdot * dP / (rho_nak * eta_pump)

    pump_mass = 2 * 30.0 + 20.0 + 40.0   # two EM pumps, controller, manifolds

    hp_system(D, n) = begin
        t_wall = 0.06 * D
        r_o, r_i = D / 2, D / 2 - t_wall
        A_metal = pi * (r_o^2 - r_i^2)
        m_tube = 8900.0 * A_metal * 1.0
        # The wick is a thin annular layer (8 % of D thick), so both its
        # cross-section and its mass scale with D^2; 0.05 kg is the allowance
        # for the 1.425 cm Option-B pipe.
        m_wick = 0.05 * (D / 0.01425)^2
        n * (m_tube + m_wick) * 1.30
    end

    o = isr_options(; T = T)
    m_A = hp_system(o.A.D_required, c.n_pins)
    m_B = hp_system(o.B.D_interstitial, o.B.n_pipes)
    m_C = hp_system(c.channel_id, c.n_pins)

    mark1_total = c.mass + pump_mass
    massA = c.mass - 0.01 * o.A.fuel_loss_pct * 155.65 + m_A
    massB = c.mass + o.B.core_block_mass_delta + o.B.reflector_mass_delta + m_B
    massC = c.mass + m_C

    return (mdot_kg_s = mdot, pump_power_W = P_pump,
            pump_power_fraction = P_pump / Q,
            pump_system_mass_kg = pump_mass,
            hp_mass_B_kg = m_B,
            hp_mass_A_kg = m_A,
            hp_mass_C_kg = m_C,
            cooling_mass_saving_B_kg = pump_mass - m_B,
            cooling_mass_saving_fraction = (pump_mass - m_B) / pump_mass,
            mark1_total_kg = mark1_total,
            optionA_total_kg = massA,
            optionB_total_kg = massB,
            optionC_total_kg = massC,
            optionA_specific_kg_kW = massA / (c.P_th / 1000),
            optionB_specific_kg_kW = massB / (c.P_th / 1000),
            optionC_specific_kg_kW = massC / (o.C.Q_total / 1000),
            mark1_specific_kg_kW = mark1_total / (c.P_th / 1000),
            n_pipes_B = o.B.n_pipes,
            m_per_pipe_B = (m_B / o.B.n_pipes) / 1.30)
end

